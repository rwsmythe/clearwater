"""The video sink: corrected frames to HEVC in MP4 with the source's timing (WP3.10, IF-5).

:class:`FFmpegVideoSink` runs ONE FFmpeg process per output (WP1.5's SIMPLE approach). Its
first input is the corrected frames, framed with their exact pts by :mod:`.nut` on the
process's standard input; its second input is the source file itself. Audio is stream-copied.
Non-timecode data tracks tagged in ``MP4_DATA_CODEC_TAGS`` are also stream-copied; other data
tracks are reported not carried (D105). These copied streams are never decoded or opened
here. Container and video-stream metadata are taken from the source. The timecode track is
regenerated by the MP4 muxer from the copied timecode tag (the muxer cannot copy it).

Timing (D94, D95, D105, AD-22): ``-copyts`` keeps every pts as written, so the start offset is
kept; ``-fps_mode passthrough`` and ``-enc_time_base:v demux`` stop FFmpeg from retiming a
variable-rate stream; ``-video_track_timescale`` keeps the source's ticks; the end sentinel of
:mod:`.nut` gives the last frame its source duration. FFmpeg writes the video edit list from the
pts it receives; for a B-frame source its ``media_time`` may differ from the source's while the
presentation is the same (AD-22), and an absent source edit list becomes an identity list (AD-22
extended). Edit lists of any other form are refused at :meth:`FFmpegVideoSink.open`.

Rate (D75, AD-12): libx265 runs at a constant ``-crf``. NVENC runs at a constant ``-cq`` under a
ceiling (:func:`nvenc_rate`) set from the output's pixel rate, halved for Standard and halved
again for Draft, and capped by an HEVC source's own Main-tier level. Left to itself, NVENC picks
the lowest level the picture size allows and caps the rate under it, so the three levels came
out at one rate on busy 4K; given a ``-maxrate`` alone, it SILENTLY switches to the High tier
once the ceiling passes the Main-tier cap of that level, even with ``-tier main``. So the sink
sets ``-tier main`` and an explicit ``-level`` (the lowest Main-tier level that holds both the
ceiling and the picture format), and ``close`` warns when the output still signals a higher
level or tier than an HEVC source's own.

Colour (D54, D55, D114): the frames are converted to the source's Y'CbCr matrix, range, chroma
subsampling and siting by :func:`clearwater.color.encode_filter`, and the output is tagged with
the source's resolved colour description, the D54 assumed values included (with a warning).

A refusal at :meth:`FFmpegVideoSink.open` (before FFmpeg is started) leaves ``out_path`` as it
was, for :meth:`FFmpegVideoSink.abort` or the caller's ``SafeWrite`` to delete. Any other failure
-- FFmpeg cannot be started, or a failure in ``open`` after it starts, in ``write`` or in
``close`` -- stops the encoder, deletes the output file and raises the original error; an error
while cleaning up is attached to it as a note, never in its place (DR-20 (6)).
:meth:`FFmpegVideoSink.close` first refuses frames that are not the source's whole readable video
(:func:`.verify.missing_frames`), then reads the finished output back and checks the MANDATORY
items it can see without decoding (:mod:`.verify`); a mismatch is a failure like any other.
"""

