class VideoEncodeError(Exception):
    """An output cannot be written: refused, unavailable, a bad frame, or FFmpeg failed.

    Attributes:
        kind: ``"refused"`` (the source or an option is outside what the sink handles, named
            in the message), ``"unavailable"`` (the encoder or bit depth is not available
            here, D74), ``"frame"`` (a written frame breaks a rule: time base, pts order,
            shape, type or device), ``"encoder_failed"`` (FFmpeg stopped or could not start;
            the message carries the end of its error output), ``"verify_failed"`` (the
            finished output does not match what was written, D94), ``"state"`` (a call out of
            order) or ``"missing_tool"`` (no ``ffmpeg`` or ``ffprobe``).
    """

    def __init__(self, kind: EncodeErrorKind, message: str) -> None:
        """Store the kind and the user-readable message.

        Args:
            kind: The reason class.
            message: A message the GUI can show (ASCII-safe).
        """
        super().__init__(message)
        self.kind: EncodeErrorKind = kind


def provenance_comment(provenance: Mapping[str, Any] | None) -> str:
    """Serialise a provenance object for the MP4 ``comment`` tag (D91, AD-13).

    Args:
        provenance: The provenance object, or None for none.

    Returns:
        Compact ASCII JSON, or the empty string for None (which clears any comment the source
        carries).

    Raises:
        VideoEncodeError: ``"refused"`` for a non-string key, a value JSON cannot hold (a NaN
            or infinity included), or JSON over :data:`PROVENANCE_MAX_BYTES`.
    """
    if provenance is None:
        return ""
    try:
        check_string_keys(provenance, "provenance")
        text = json.dumps(provenance, ensure_ascii=True, allow_nan=False, separators=(",", ":"))
    except (FormatError, TypeError, ValueError) as error:
        raise VideoEncodeError(
            "refused", f"The provenance cannot be embedded: {ascii_text(str(error))}"
        ) from error
    if len(text) > PROVENANCE_MAX_BYTES:
        raise VideoEncodeError(
            "refused",
            f"The provenance is {len(text)} bytes as JSON; at most {PROVENANCE_MAX_BYTES} can be "
            "embedded.",
        )
    return text


@dataclass(frozen=True)
class NvencRate:
    """NVENC's rate ceiling for one output (:func:`nvenc_rate`).

    Attributes:
        maxrate: ``-maxrate`` in bits per second.
        bufsize: ``-bufsize`` in bits (equal to ``maxrate``: one second).
        level: ``-level`` as FFmpeg spells it, for example ``"5.2"``; always with ``-tier main``.
    """

    maxrate: int
    bufsize: int
    level: str


def _main_tier_cap(level_idc: int) -> int | None:
    """Return a level's Main-tier MaxBR in bits per second, or None for an unknown level."""
    return next((cap for idc, _, _, cap in HEVC_MAIN_TIER_LEVELS if idc == level_idc), None)


def nvenc_rate(
    width: int, height: int, frame_rate: Fraction, quality: str, source_level: HevcLevel | None
) -> NvencRate:
    """Return NVENC's rate ceiling and level for an output (AD-12 as amended).

    The High ceiling is :data:`NVENC_BITS_PER_PIXEL` times the output's pixel rate, rounded
    down; for an HEVC source signalling a Main-tier level it is at most that level's Main-tier
    cap (a source signalling the High tier, a level this table does not know, or no level --
    an H.264 source -- leaves the pixel-rate ceiling alone). Standard is half the High
    ceiling and Draft a quarter. The level is the lowest Main-tier level that holds the
    picture (luma picture size, each dimension, luma sample rate) and the ceiling; a ceiling
    above every Main-tier cap that holds the picture is cut to the highest such cap.

    Args:
        width: The output width in pixels.
        height: The output height in pixels.
        frame_rate: The frames per second (the source's average for a variable-rate source).
        quality: ``"high"``, ``"standard"`` or ``"draft"``.
        source_level: The level and tier the source signals, or None (not HEVC, or unread).

    Returns:
        The ceiling, the buffer and the level.

    Raises:
        ValueError: If the frame rate is not positive or no HEVC level holds the picture.
    """
    if frame_rate <= 0:
        raise ValueError(f"the frame rate {frame_rate} is not positive")
    high = int(NVENC_BITS_PER_PIXEL * width * height * frame_rate)
    if source_level is not None and not source_level.high_tier:
        cap = _main_tier_cap(source_level.level_idc)
        if cap is not None:
            high = min(high, cap)
    maxrate = max(high // NVENC_RATE_SHARE[quality], 1)
    luma = width * height
    fitting = [
        (idc, cap)
        for idc, picture, rate, cap in HEVC_MAIN_TIER_LEVELS
        if luma <= picture and max(width, height) ** 2 <= 8 * picture and luma * frame_rate <= rate
    ]
    if not fitting:
        raise ValueError(f"no HEVC level holds {width}x{height} at {float(frame_rate):.3f} fps")
    idc, cap = next(((i, c) for i, c in fitting if c >= maxrate), fitting[-1])
    maxrate = min(maxrate, cap)
    return NvencRate(maxrate=maxrate, bufsize=maxrate, level=f"{idc / 30:.1f}")


def level_warning(source: HevcLevel | None, output: HevcLevel | None) -> str | None:
    """Return a warning when the output signals a higher HEVC level or tier than the source.

    Args:
        source: The level and tier an HEVC source signals, or None (not HEVC, or unread).
        output: The level and tier the output signals, or None (unread).

    Returns:
        The warning, or None when either is unknown or the output is not higher.
    """
    if source is None or output is None:
        return None
    if output.level_idc <= source.level_idc and (source.high_tier or not output.high_tier):
        return None
    return (
        f"The output signals HEVC level {output.name}, above the source's own {source.name}; "
        "a player that plays the source may not play the output."
    )


def _encoder_options(
    encoder: str, quality: str, bit_depth: int, rate: NvencRate | None
) -> list[str]:
    """Return the encoder, rate control, pixel format and profile options (AD-12)."""
    value = str((NVENC_CQ if encoder == HARDWARE_ENCODER else X265_CRF)[quality])
    if encoder == HARDWARE_ENCODER:
        assert rate is not None  # encode_command computes it for NVENC
        options = ["-c:v", encoder, "-preset", "p5", "-tune", "hq", "-rc", "vbr", "-b:v", "0"]
        options += ["-cq", value, "-maxrate", str(rate.maxrate), "-bufsize", str(rate.bufsize)]
        options += ["-tier", "main", "-level", rate.level]
        pix_fmt = "p010le" if bit_depth == 10 else "yuv420p"
    else:
        options = ["-c:v", encoder, "-preset", "medium", "-crf", value]
        options += ["-x265-params", "log-level=error"]
        pix_fmt = "yuv420p10le" if bit_depth == 10 else "yuv420p"
    return [*options, "-pix_fmt", pix_fmt, "-profile:v", "main10" if bit_depth == 10 else "main"]


def _seconds(value: Fraction) -> str:
    """Format a non-negative time for an FFmpeg option, rounded up to a microsecond."""
    micro = -((-value.numerator * 1_000_000) // value.denominator)
    return f"{micro // 1_000_000}.{micro % 1_000_000:06d}"


def encode_command(
    ffmpeg: Path,
    probe: ProbeResult,
    out_path: Path,
    *,
    encoder: str,
    quality: str,
    bit_depth: int,
    comment: str,
    cut_at: Fraction | None,
    source_level: HevcLevel | None = None,
) -> list[str]:
    """Return the one FFmpeg command that encodes the piped frames and muxes the source's tracks.

    The arguments are not validated here; :meth:`FFmpegVideoSink.open` does that first.

    Args:
        ffmpeg: The ``ffmpeg`` executable.
        probe: The source's probe result (its path is the second input).
        out_path: The output file; overwritten (``-y``: the caller's temporary exists, empty).
        encoder: ``"hevc_nvenc"`` or ``"libx265"``.
        quality: ``"high"``, ``"standard"`` or ``"draft"``.
        bit_depth: The output bit depth (the source's, or 10 for an 8-bit source, D76).
        comment: The provenance JSON, or the empty string.
        cut_at: Where to stop reading the source's audio and data tracks, as FFmpeg's input
            ``-to`` reads it (seconds after the input's start), or None to copy them whole.
        source_level: The HEVC level and tier the source signals, for NVENC's ceiling
            (:func:`nvenc_rate`), or None.

    Returns:
        The command.

    Raises:
        ValueError: For NVENC, if :func:`nvenc_rate` cannot set a ceiling for the picture.
    """
    video = probe.video
    names = ffmpeg_color_names(video.color)
    tags: list[str] = []
    params: list[str] = []
    for key, param in (
        ("color_primaries", "color_primaries"),
        ("color_trc", "color_trc"),
        ("colorspace", "colorspace"),
        ("color_range", "range"),
    ):
        if key in names:
            tags += [f"-{key}", names[key]]
            params.append(f"{param}={names[key]}")
    vf = encode_filter(video, bit_depth=bit_depth)
    if params:
        vf += ",setparams=" + ":".join(params)  # raw frames carry no tags; set them on frames
    maps = ["-map", "0:v:0"]
    for audio in probe.audio:
        maps += ["-map", f"1:{audio.index}"]
    for data in probe.data:
        if data.codec_tag != TIMECODE_TAG and data.codec_tag in MP4_DATA_CODEC_TAGS:
            maps += ["-map", f"1:{data.index}"]
    rotation = ["-display_rotation", str(video.rotation)] if video.rotation else []
    cut = ["-to", _seconds(cut_at)] if cut_at is not None else []
    rate = None
    if encoder == HARDWARE_ENCODER:
        rate = nvenc_rate(video.width, video.height, video.frame_rate, quality, source_level)
    return [
        str(ffmpeg),
        "-nostdin",
        "-hide_banner",
        "-nostats",
        "-loglevel",
        "error",
        "-y",
        "-copyts",
        "-noautorotate",
        *rotation,
        "-bsf:v",
        nut.INPUT_BITSTREAM_FILTER,
        "-f",
        "nut",
        "-i",
        "pipe:0",
        *cut,
        "-i",
        str(probe.path.absolute()),  # absolute: a relative name could read as an option
        *maps,
        "-vf",
        vf,
        *_encoder_options(encoder, quality, bit_depth, rate),
        *tags,
        "-tag:v",
        "hvc1",
        "-fps_mode",
        "passthrough",
        "-enc_time_base:v",
        "demux",
        "-video_track_timescale",
        str(video.time_base.denominator),
        "-c:a",
        "copy",
        "-c:d",
        "copy",
        "-map_metadata",
        "1",
        "-map_metadata:s:v:0",
        "1:s:v:0",
        "-write_tmcd",
        "1",
        "-metadata",
        f"{PROVENANCE_TAG}={comment}",
        "-movflags",
        "+negative_cts_offsets",
        "-f",
        "mp4",
        str(out_path.absolute()),
    ]


def _edit_list_refusal(probe: ProbeResult, table: PacketTable) -> str | None:
    """Return why the source's video edit list is a form the sink cannot reproduce, or None.

    Reproduced: none (absent), one media segment, or an empty edit followed by one media
    segment, every rate 1, with the media segment starting at the track's earliest composition
    time from its sample table (identity, or AD-22's reorder delay; anything else is a trim,
    round-2 #2), the first frame presented where the media segment starts (no head trim) and
    the last frame starting before the presentation ends (no tail trim).
    """
    edits = probe.edit_list
    if not edits:
        return None
    if any(e.media_rate != 1 for e in edits):
        return "an edit list that changes the playback rate"
    empties = [e for e in edits if e.media_time_s is None]
    media = [e for e in edits if e.media_time_s is not None]
    if len(media) != 1 or len(empties) > 1 or (empties and edits[0].media_time_s is not None):
        return "an edit list with several segments"
    start = media[0].media_time_s
    if table.samples is not None and start != table.samples.earliest:
        return (
            f"an edit list whose media segment starts at {start} s rather than at the video's "
            f"earliest frame ({table.samples.earliest} s)"
        )
    dwell = empties[0].segment_duration_s if empties else Fraction(0)
    time_base = probe.video.time_base
    first = min(table.video_pts, default=0) * time_base
    if first != dwell:
        return "an edit list that trims the start of the video"
    if table.video_pts and presentation_end(probe, table) <= max(table.video_pts):
        return "an edit list that trims the end of the video"
    return None


def _source_level(probe: ProbeResult) -> HevcLevel | None:
    """Return the HEVC level and tier the source signals; None when not HEVC or unreadable."""
    if probe.video.codec != "hevc":
        return None
    try:
        return read_hevc_level(probe.path)
    except (BoxError, OSError):
        return None  # then the pixel-rate ceiling alone


def _remove(path: Path) -> None:
    """Delete a file, retrying briefly while a just-ended process still holds it (Windows)."""
    for attempt in range(_REMOVE_TRIES):
        try:
            path.unlink(missing_ok=True)
            return
        except PermissionError:
            if attempt == _REMOVE_TRIES - 1:
                raise
            time.sleep(_REMOVE_PAUSE_S)


def _assumed_color_warning(names: Mapping[str, str]) -> str:
    """Describe D54's assumptions and the resolved output colour tags.

    Mention limited range only for resolved ``color_range tv``; omit that clause
    for full range (``pc``). The probe defaults a range only to limited. Full
    range is tagged or derived from a yuvj pixel format, never assumed.

    Args:
        names: FFmpeg option names and values for the resolved colour description.

    Returns:
        The warning with the resolved tags listed in their mapping order.
    """
    shown = ", ".join(f"{k} {v}" for k, v in names.items())
    range_clause = " and limited range" if names.get("color_range") == "tv" else ""
    return (
        "The source's colour tags are missing or unexpected; Clearwater assumed BT.709 "
        f"colours{range_clause} for the missing or unexpected ones, and the output is "
        f"tagged with these values ({shown})."
    )


class FFmpegVideoSink:
    """Writes corrected frames to an HEVC MP4 with the source's timing and tracks (IF-5).

    One sink writes one output: ``open``, ``write`` per frame in pts order, then ``close`` (or
    ``abort``). Any failure is final: the sink accepts nothing more except ``abort``. A refusal
    at ``open`` leaves ``out_path`` to ``abort`` (or the caller's ``SafeWrite``); every other
    failure stops the encoder and deletes the output, and ``abort`` then only repeats that.
    """

    def __init__(self, *, device_backend: object | None = None) -> None:
        """Create a sink that has not been opened.

        Args:
            device_backend: The job's backend. When it satisfies
                :class:`~clearwater.io.video.decode.DeviceFrameBackend` (the GPU backend, AD-29),
                a frame on its device is quantised there and only its planes are downloaded.
                None (the default) or a backend without the device extensions (the CPU backend)
                keeps the host-only rule: a frame not on ``"cpu"`` is refused.
        """
        self._device_backend = (
            device_backend if isinstance(device_backend, DeviceFrameBackend) else None
        )
        self._phase: _Phase = "new"
        self._phase_lock = threading.Lock()  # close's and abort's transitions (DR-63)
        self._process: subprocess.Popen[bytes] | None = None
        self._stdin: IO[bytes] | None = None
        self._stderr_thread: threading.Thread | None = None
        self._stderr_tail: collections.deque[bytes] = collections.deque()
        self._stderr_size = 0
        self._stderr_lock = threading.Lock()
        self._out_path: Path | None = None
        self._probe: ProbeResult | None = None
        self._source: PacketTable | None = None
        self._source_pts: frozenset[int] = frozenset()
        self._bit_depth = 8
        self._shape = (0, 0, 3)
        self._written: list[int] = []
        self._warnings: list[str] = []
        self._audio_end: Fraction | None = None
        self._source_level: HevcLevel | None = None
        self.nvenc_rate: NvencRate | None = None
        """NVENC's ceiling and level chosen at ``open`` (:func:`nvenc_rate`); None for libx265
        or before ``open``. ``SinkReport`` (IF-5, frozen) has no field for it."""

    # --- IF-5 -------------------------------------------------------------------------------

    def capabilities(self) -> tuple[EncoderCapability, ...]:
        """Return the encoder options and whether each is available (D74).

        Returns:
            One entry per encoder (``hevc_nvenc``, ``libx265``), detected once per process.
        """
        return detect_capabilities()

    def open(
        self,
        probe: ProbeResult,
        out_path: Path,
        *,
        encoder: str,
        quality: str,
        bit_depth: int,
        provenance: Mapping[str, Any] | None,
    ) -> None:
        """Check every option, then start the encoder writing ``out_path`` (AD-12 levels).

        Everything is refused before FFmpeg starts, with the cause named: a probe with a
        ``"refuse"`` fault; ``"auto"`` (resolve it first with
        :func:`~clearwater.io.video.capability.resolve_encoder`) or an unknown or unavailable
        encoder; a bit depth that is not the source's own or 10 for an 8-bit source (D76), or
        that the encoder cannot write; an unknown quality level; a provenance object JSON cannot
        hold; a stated non-square pixel aspect ratio (CHARC P8; a ratio that cannot be seen is
        treated as 1:1); an edit list the sink cannot reproduce; a frame with a negative pts.
        ``out_path`` is recorded first, so :meth:`abort` after a refusal still deletes it. A
        refusal is final: the sink cannot be opened again (use a new sink).

        Args:
            probe: The source's probe result.
            out_path: The output file. It is overwritten: the caller's ``SafeWrite``
                temporary, which exists empty; never a final name.
            encoder: ``"hevc_nvenc"`` or ``"libx265"`` (already resolved, never ``"auto"``).
            quality: ``"high"``, ``"standard"`` or ``"draft"`` (D75).
            bit_depth: 8 or 10: the source's own, or 10 for an 8-bit source (D76).
            provenance: The provenance to embed in the ``comment`` tag (D91), or None.

        Raises:
            VideoEncodeError: ``"state"`` when already opened; ``"refused"``,
                ``"unavailable"`` or ``"missing_tool"`` as above; ``"encoder_failed"`` when
                FFmpeg cannot be started or stops at once (the output is deleted).
        """
        if self._phase != "new":
            raise VideoEncodeError(
                "state", f"A video output cannot be opened twice ({self._phase})."
            )
        self._out_path = out_path  # first: abort() deletes it even after a refusal below
        try:
            command, header = self._prepare(
                probe,
                out_path,
                encoder=encoder,
                quality=quality,
                bit_depth=bit_depth,
                provenance=provenance,
            )
        except BaseException:
            self._phase = "failed"  # a refusal is final (round-4 #3); abort still deletes out_path
            raise
        self._start(self._command(command))
        try:
            self._send(header)
        except BaseException as error:
            self._fail(error)

    def _prepare(
        self,
        probe: ProbeResult,
        out_path: Path,
        *,
        encoder: str,
        quality: str,
        bit_depth: int,
        provenance: Mapping[str, Any] | None,
    ) -> tuple[list[str], bytes]:
        """Run every check of :meth:`open`; return the FFmpeg command and the NUT stream header."""
        self._warnings = []
        self._audio_end = None
        for fault in probe.faults:
            if fault.severity == "refuse":
                raise VideoEncodeError("refused", fault.message)
        self._check_options(encoder, quality, bit_depth)
        try:
            encode_pix_fmt(probe.video, bit_depth=bit_depth)
        except ColorError as error:
            raise VideoEncodeError(
                "refused", f"This video cannot be written: {ascii_text(str(error))}"
            ) from error
        if probe.video.time_base.numerator != 1:
            raise VideoEncodeError(
                "refused", f"The video's time base {probe.video.time_base} is not 1/N ticks."
            )
        comment = provenance_comment(provenance)
        try:
            ffmpeg = find_tool("ffmpeg")
            source = read_packet_table(probe.path)
        except VideoProbeError as error:
            kind: EncodeErrorKind = "missing_tool" if error.kind == "missing_tool" else "refused"
            raise VideoEncodeError(kind, str(error)) from error
        self._check_source(probe, source)
        source_level = _source_level(probe)
        rate = None
        if encoder == HARDWARE_ENCODER:
            video = probe.video
            try:
                rate = nvenc_rate(
                    video.width, video.height, video.frame_rate, quality, source_level
                )
            except ValueError as error:
                raise VideoEncodeError(
                    "refused", f"This video cannot be written: {ascii_text(str(error))}"
                ) from error
        cut_at = self._plan_tracks(probe, source)
        self._probe, self._source = probe, source
        self._source_pts = frozenset(source.video_pts)
        self._bit_depth = bit_depth
        self._shape = (probe.video.height, probe.video.width, 3)
        if probe.video.color.assumed:
            names = ffmpeg_color_names(probe.video.color)
            self._warnings.append(_assumed_color_warning(names))
        command = encode_command(
            ffmpeg,
            probe,
            out_path,
            encoder=encoder,
            quality=quality,
            bit_depth=bit_depth,
            comment=comment,
            cut_at=cut_at,
            source_level=source_level,
        )
        self._source_level, self.nvenc_rate = source_level, rate
        try:  # built before FFmpeg starts, so a failure here leaves nothing running
            header = nut.stream_header(
                width=probe.video.width,
                height=probe.video.height,
                bit_depth=bit_depth,
                time_base=probe.video.time_base,
                frame_rate=probe.video.frame_rate,
            )
        except ValueError as error:
            raise VideoEncodeError(
                "refused", f"This video cannot be written: {ascii_text(str(error))}"
            ) from error
        return command, header

    def write(self, frame: Frame) -> None:
        """Write one frame, in pts order, with its exact pts.

        The sink preserves pts, start offset, edit list (AD-22), audio, timecode (regenerated)
        and rotation. Non-timecode data tracks tagged in ``MP4_DATA_CODEC_TAGS`` are
        stream-copied; others are reported not carried (D105). The frame is quantised at the
        OUTPUT bit depth.

        Args:
            frame: The corrected frame: float32 ``(height, width, 3)``, the source's time base,
                a pts of the source later than the previous frame's. On the CPU a NumPy array.
                On the device of the sink's ``device_backend`` (WP3.21 #2, AD-29) an array of
                that backend, quantised there and downloaded as planes. Any other device label,
                and a device label on host pixels, is refused (call the backend's ``to_host``
                and label the frame ``"cpu"``).

        Raises:
            VideoEncodeError: ``"state"`` when not open; ``"frame"`` for a frame that breaks a
                rule above; ``"encoder_failed"`` when FFmpeg has stopped. The output is deleted.
        """
        if self._phase != "open":
            raise VideoEncodeError("state", f"No video output is open ({self._phase}).")
        try:
            pts, payload = self._payload(frame)
            self._poll()
            self._send(nut.frame_header(pts, len(payload)))
            self._send(payload)
        except BaseException as error:
            self._fail(error)
        self._written.append(pts)

    def close(self) -> SinkReport:
        """End the stream, wait for FFmpeg, verify the output (D94) and report.

        Returns:
            The frames written, the warnings (assumed colour tags, a cut-short source), and the
            best-effort items of the source the output does not carry (D105).

        Raises:
            VideoEncodeError: ``"state"`` when not open or nothing was written;
                ``"verify_failed"`` when the frames written are not the source's whole
                readable video (checked before the stream is ended) or the output does not
                match what was written; ``"encoder_failed"`` when FFmpeg fails. The output is
                deleted.
        """
        if self._phase != "open":
            raise VideoEncodeError("state", f"No video output is open ({self._phase}).")
        try:
            if not self._written:
                raise VideoEncodeError("state", "No frames were written, so there is no video.")
            self._check_complete()
            report = self._finish()
        except BaseException as error:
            self._fail(error)
        with self._phase_lock:
            if self._phase == "open":  # an abort that landed during _finish stays (DR-63)
                self._phase = "closed"
        return report

    def abort(self) -> None:
        """Stop and remove the partial output (D44, D85).

        Idempotent and never raises: it may run while another error is being handled, and that
        error must stay the one reported (DR-20 (6)). Deletes ``out_path`` and nothing else.
        After a failure or an earlier ``abort`` whose cleanup did not finish, it tries again
        (stops FFmpeg if it still runs, deletes ``out_path`` if it is still there); after a
        successful ``close`` it does nothing (the output is the caller's).

        The window (DR-63): an ``abort`` from another thread while ``close`` is still running
        (after its last check, before it returns) deletes the output, and ``close`` then
        returns its report for a file that is gone; the phase stays ``"aborted"``, so a later
        ``abort`` tries the cleanup again. The caller decides by its own cancel state after
        ``close``, never by ``close`` having returned.
        """
        with self._phase_lock:
            if self._phase == "closed":
                return
            if self._phase in ("new", "open"):
                self._phase = "aborted"
        with contextlib.suppress(Exception):
            self._cleanup()

    # --- open -------------------------------------------------------------------------------

    def _check_options(self, encoder: str, quality: str, bit_depth: int) -> None:
        """Refuse an unresolved, unknown or unavailable encoder, bit depth or quality level."""
        if encoder == AUTO:
            raise VideoEncodeError(
                "refused", 'The encoder "auto" must be resolved before export (resolve_encoder).'
            )
        if encoder not in ENCODERS:
            raise VideoEncodeError(
                "refused",
                f"The encoder {ascii_text(str(encoder))!r} is not one of: " + ", ".join(ENCODERS),
            )
        if type(bit_depth) is not int or bit_depth not in BIT_DEPTHS:
            raise VideoEncodeError(
                "refused", f"The output bit depth {bit_depth!r} is not one of: 8, 10."
            )
        if quality not in QUALITY_LEVELS:
            raise VideoEncodeError(
                "refused",
                f"The quality level {ascii_text(str(quality))!r} is not one of: "
                + ", ".join(QUALITY_LEVELS),
            )
        capability = next((c for c in self.capabilities() if c.name == encoder), None)
        if capability is None or not capability.available:
            reason = capability.reason if capability is not None else None
            raise VideoEncodeError(
                "unavailable", f"The {encoder} encoder is not available: {reason or 'unknown'}"
            )
        if bit_depth not in capability.bit_depths:
            raise VideoEncodeError(
                "unavailable", f"The {encoder} encoder cannot write {bit_depth}-bit video here."
            )

    def _check_source(self, probe: ProbeResult, source: PacketTable) -> None:
        """Refuse non-square pixels, an edit list the sink cannot reproduce, or a negative pts."""
        ratio = source.video.sample_aspect_ratio
        if not square_pixels(ratio):
            raise VideoEncodeError(
                "refused",
                f"The video has non-square pixels (sample aspect ratio {ascii_text(str(ratio))}), "
                "which is not supported.",
            )
        if not source.video_pts:
            raise VideoEncodeError("refused", "The video has no frames with a timestamp.")
        refusal = _edit_list_refusal(probe, source)
        if refusal is not None:
            raise VideoEncodeError("refused", f"The video has {refusal}, which is not supported.")
        first = min(source.video_pts)
        if first < 0:  # legal ISO (no edit list, negative composition times); NUT pts are unsigned
            raise VideoEncodeError(
                "refused",
                f"The video has frames with negative timestamps (from {first} ticks), which is "
                "not supported.",
            )

    def _plan_tracks(self, probe: ProbeResult, source: PacketTable) -> Fraction | None:
        """Decide how the audio and data tracks end for a cut-short source (D86, Q-B).

        A truncated file: the tracks are cut where its readable video ends, the end of its last
        readable frame read from the source's sample table (:func:`.verify.readable_end`;
        refused when it cannot be told). An unreadable tail:
        the tracks are copied whole, and a warning says they run past the last video frame.

        Returns:
            The ``-to`` value for the source input, or None. FFmpeg (9.0.2) applies an input
            ``-to`` under ``-copyts`` relative to the input's start time (the earliest start of
            any of its streams), so the value is the video end minus that start.
        """
        kinds = {fault.kind for fault in probe.faults}
        if "truncated" in kinds:
            readable = readable_video_pts(probe, source)  # the completeness rule's set too
            if not readable:
                raise VideoEncodeError("refused", "The video has no readable frame.")
            try:
                end = readable_end(probe, source, readable[-1])
            except VideoProbeError as error:
                raise VideoEncodeError("refused", str(error)) from error
            self._warnings.append(
                "The source is cut short; the output ends at its last readable frame, and the "
                "audio and other tracks are cut at the same point."
            )
            starts = [
                s.start_pts * s.time_base
                for s in source.streams
                if s.start_pts is not None and s.time_base is not None
            ]
            self._audio_end = end * probe.video.time_base
            return self._audio_end - min(starts, default=Fraction(0))
        if "unreadable_tail" in kinds:
            self._warnings.append(
                "The end of the source cannot be decoded; the output's video stops at the last "
                "readable frame, while its audio and other tracks are kept whole and run longer."
            )
        return None

    def _command(self, command: list[str]) -> list[str]:
        """Return the command to run (a seam for tests that capture the pipe instead)."""
        return command

    def _start(self, command: list[str]) -> None:
        """Start FFmpeg with stdin piped and a thread draining its stderr into a bounded tail."""
        try:
            process = subprocess.Popen(
                command,
                stdin=subprocess.PIPE,
                stdout=subprocess.DEVNULL,
                stderr=subprocess.PIPE,
                **tool_spawn_kwargs(),
            )
        except OSError as error:
            failure = VideoEncodeError(
                "encoder_failed", f"FFmpeg could not be started: {ascii_text(str(error))}"
            )
            failure.__cause__ = error
            self._fail(failure)  # final, and out_path deleted like any failure (Reviewer B #7)
        self._process = process
        self._stdin = process.stdin
        self._phase = "open"
        try:  # FFmpeg runs from here: any failure goes through _fail (round-4 #1)
            stderr = process.stderr
            assert stderr is not None  # stderr=PIPE
            thread = threading.Thread(target=self._drain, args=(stderr,), daemon=True)
            thread.start()
        except BaseException as error:
            if isinstance(error, Exception):
                failure = VideoEncodeError(
                    "encoder_failed",
                    f"FFmpeg's error output cannot be read: {ascii_text(str(error))}",
                )
                failure.__cause__ = error
                error = failure
            self._fail(error)
        self._stderr_thread = thread

    def _drain(self, stream: IO[bytes]) -> None:
        """Read FFmpeg's stderr to its end, keeping only the last few kilobytes."""
        with contextlib.suppress(OSError, ValueError):
            for chunk in iter(lambda: stream.read(4096), b""):
                with self._stderr_lock:
                    self._stderr_tail.append(chunk)
                    self._stderr_size += len(chunk)
                    while self._stderr_size > STDERR_TAIL_BYTES and len(self._stderr_tail) > 1:
                        self._stderr_size -= len(self._stderr_tail.popleft())

    def _stderr_text(self) -> str:
        """Return the kept end of FFmpeg's stderr as ASCII-safe text."""
        with self._stderr_lock:
            data = b"".join(self._stderr_tail)[-STDERR_TAIL_BYTES:]
        lines = [line.strip() for line in data.decode("utf-8", errors="replace").splitlines()]
        return ascii_text(" | ".join(line for line in lines if line)[-1500:])

    # --- write and close --------------------------------------------------------------------

    def _payload(self, frame: Frame) -> tuple[int, bytes]:
        """Check one frame against the rules of :meth:`write`; return its pts and its planes."""
        probe = self._probe
        assert probe is not None
        pixels: Any = frame.pixels  # on a device, an array of that backend (IF-1 types the host's)
        backend = self._device_backend
        on_device = frame.device != "cpu"
        if on_device and (
            backend is None or frame.device != backend.device or isinstance(pixels, np.ndarray)
        ):
            raise VideoEncodeError(
                "frame",
                f"The frame is on {ascii_text(str(frame.device))}; copy it to the host first "
                "(backend.to_host).",
            )
        if frame.time_base != probe.video.time_base:
            raise VideoEncodeError(
                "frame",
                f"The frame's time base {frame.time_base} is not the source's "
                f"{probe.video.time_base}.",
            )
        ticks: object = frame.pts_ticks
        if isinstance(ticks, bool) or not isinstance(ticks, int | np.integer):
            raise VideoEncodeError("frame", f"The frame pts {ticks!r} is not an integer.")
        pts = int(ticks)
        if pts not in self._source_pts:
            raise VideoEncodeError("frame", f"The frame pts {pts} is not a pts of the source.")
        if self._written and pts <= self._written[-1]:
            raise VideoEncodeError(
                "frame", f"The frame pts {pts} does not follow the previous {self._written[-1]}."
            )
        if not on_device and (not isinstance(pixels, np.ndarray) or pixels.dtype != np.float32):
            raise VideoEncodeError(
                "frame", f"The frame is {type(pixels).__name__}, not a float32 NumPy array."
            )
        if on_device and getattr(pixels, "dtype", None) != np.float32:
            dtype = getattr(pixels, "dtype", None)
            raise VideoEncodeError("frame", f"The device frame is {dtype}, not float32.")
        if pixels.shape != self._shape:
            raise VideoEncodeError(
                "frame", f"The frame shape {pixels.shape} is not the source's {self._shape}."
            )
        if on_device:
            assert backend is not None
            try:
                return pts, backend.rgb_to_planes(pixels, bit_depth=self._bit_depth)
            except (TypeError, ValueError) as error:  # not this backend's array, or a NaN
                raise VideoEncodeError("frame", ascii_text(str(error))) from error
        try:
            return pts, rgb_to_planes(np.ascontiguousarray(pixels), bit_depth=self._bit_depth)
        except ColorError as error:
            raise VideoEncodeError("frame", ascii_text(str(error))) from error

    def _poll(self) -> None:
        """Raise when FFmpeg has stopped (checked before every write and inside every wait)."""
        process = self._process
        if process is not None and process.poll() is not None:
            raise self._encoder_failed(process.returncode)

    def _encoder_failed(self, status: int | None) -> VideoEncodeError:
        """Build the error for an encoder that stopped, with the end of its stderr."""
        if self._stderr_thread is not None:
            self._stderr_thread.join(timeout=2)
        tail = self._stderr_text() or "no error output"
        return VideoEncodeError(
            "encoder_failed", f"The video encoder stopped (exit status {status}): {tail}"
        )

    def _send(self, data: bytes) -> None:
        """Write bytes to FFmpeg's stdin; a closed pipe means the encoder has stopped."""
        stdin = self._stdin
        assert stdin is not None
        try:
            stdin.write(data)
        except (BrokenPipeError, OSError) as error:
            raise self._encoder_failed(self._exit_status()) from error

    def _exit_status(self) -> int | None:
        """Wait briefly for FFmpeg to end and return its exit status (None if it still runs)."""
        process = self._process
        if process is None:
            return None
        try:
            return process.wait(timeout=10)
        except subprocess.TimeoutExpired:
            return None

    def _check_complete(self) -> None:
        """Refuse frames that are not the source's whole readable video (D94, Reviewer B #1).

        Run before the end sentinel: an incomplete export fails before FFmpeg finishes it.
        """
        probe, source = self._probe, self._source
        assert probe is not None and source is not None
        problem = missing_frames(probe, source, self._written)
        if problem is not None:
            raise VideoEncodeError("verify_failed", f"The video is incomplete: {problem}.")

    def _finish(self) -> SinkReport:
        """Send the end sentinel, wait for FFmpeg with polling, then verify the output."""
        return self._verify(self._end_stream())

    def _end_stream(self) -> int:
        """Send the end sentinel, close stdin and wait for FFmpeg; return the sentinel's pts."""
        probe, source = self._probe, self._source
        process, stdin = self._process, self._stdin
        assert probe is not None and source is not None
        assert process is not None and stdin is not None
        end = frame_end(probe, source, self._written[-1])
        self._send(nut.sentinel(end))
        try:
            stdin.close()
        except (BrokenPipeError, OSError) as error:
            raise self._encoder_failed(self._exit_status()) from error
        deadline = time.monotonic() + FINISH_TIMEOUT_S
        while True:
            try:
                status = process.wait(timeout=POLL_S)
                break
            except subprocess.TimeoutExpired:
                if time.monotonic() > deadline:
                    raise VideoEncodeError(
                        "encoder_failed",
                        f"The video encoder did not finish within {FINISH_TIMEOUT_S:g} s.",
                    ) from None
        if status != 0:
            raise self._encoder_failed(status)
        if self._stderr_thread is not None:
            self._stderr_thread.join(timeout=5)
        return end

    def _verify(self, end: int) -> SinkReport:
        """Read the finished output back, check it (D94) and build the report."""
        probe, source, out_path = self._probe, self._source, self._out_path
        assert probe is not None and source is not None and out_path is not None
        try:
            output = read_packet_table(out_path, strict=True)
        except VideoProbeError as error:
            raise VideoEncodeError(
                "verify_failed", f"The finished video cannot be read back: {error}"
            ) from error
        problems = check_output(
            out_path,
            output,
            probe=probe,
            source=source,
            written=self._written,
            end_pts=end,
            audio_end=self._audio_end,
        )
        dropped = source.pcm_dropped_bytes(output, probe=probe, audio_end=self._audio_end)
        if dropped:
            self._warnings.append(
                f"audio cut at the last whole sample frame; {dropped} bytes "
                "of a partial frame dropped"
            )
        if problems:
            raise VideoEncodeError(
                "verify_failed",
                "The finished video does not match what was written: " + "; ".join(problems),
            )
        if self._source_level is not None:
            try:
                output_level = read_hevc_level(out_path)
            except (BoxError, OSError):
                output_level = None  # the level is a warning, not a MANDATORY item
            warning = level_warning(self._source_level, output_level)
            if warning is not None:
                self._warnings.append(warning)
        return SinkReport(
            frames_written=len(self._written),
            warnings=tuple(self._warnings),
            not_carried=tuple(not_carried(probe, source, output)),
        )

    # --- failure ----------------------------------------------------------------------------

    def _fail(self, error: BaseException) -> NoReturn:
        """Stop the encoder, delete the output and raise ``error`` (never a cleanup error)."""
        self._phase = "failed"
        try:
            self._cleanup()
        except Exception as cleanup:
            error.add_note(f"While cleaning up after this error: {ascii_text(repr(cleanup))}")
        raise error

    def _cleanup(self) -> None:
        """Kill FFmpeg if it runs, close its pipes, and delete ``out_path``.

        ``out_path`` is deleted even when a process step raises (round-3 finding 1). Raises the
        process step's error, or the deletion's (with the process step's as its context).
        """
        try:
            process = self._process
            if process is not None:
                if process.poll() is None:
                    process.kill()
                with contextlib.suppress(OSError, ValueError):
                    if process.stdin is not None:
                        process.stdin.close()
                process.wait(timeout=30)
                if self._stderr_thread is not None:
                    self._stderr_thread.join(timeout=5)
        finally:
            if self._out_path is not None:
                _remove(self._out_path)
