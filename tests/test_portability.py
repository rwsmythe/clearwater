# --- W-RATE: the shared rate ceiling and the two VideoToolbox candidates (AD-12, AD-35) ------


def _independent_ceiling(
    width: int, height: int, fps: Fraction, quality: str, level: HevcLevel | None
) -> tuple[int, int]:
    """Recompute R and the level idc from AD-12's words (audit section 4, steps 1-4)."""
    high = (24 * width * height * fps.numerator) // (100 * fps.denominator)
    caps = {idc: cap for idc, _, _, cap in encode.HEVC_MAIN_TIER_LEVELS}
    if level is not None and not level.high_tier and level.level_idc in caps:
        high = min(high, caps[level.level_idc])
    r0 = max(high // {"high": 1, "standard": 2, "draft": 4}[quality], 1)
    fitting = [
        (idc, cap)
        for idc, ps, sr, cap in encode.HEVC_MAIN_TIER_LEVELS
        if width * height <= ps and max(width, height) ** 2 <= 8 * ps and width * height * fps <= sr
    ]
    idc, cap = next(((i, c) for i, c in fitting if c >= r0), fitting[-1])
    return min(r0, cap), idc


RATE_GRID = [
    (3840, 2160, Fraction(60000, 1001), HevcLevel(153, False)),  # Main-tier source cap
    (3840, 2160, Fraction(60000, 1001), HevcLevel(153, True)),  # High tier: no source cap
    (3840, 2160, Fraction(30), HevcLevel(999, False)),  # unknown level: no source cap
    (1920, 1080, Fraction(30000, 1001), None),  # H.264: no source cap, Fraction rounding
    (5312, 2988, Fraction(2997, 100), None),  # a VFR source's average
    (64, 48, Fraction(25), None),  # tiny: the lowest level
    (8192, 4320, Fraction(120), None),  # above every cap: clamped to the highest level's
]


