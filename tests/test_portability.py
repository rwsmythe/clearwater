def _fixture_text(name: str) -> str:
    return (FFMPEG_TEXT / name).read_text(encoding="utf-8")


def _stub_ffmpeg(
    monkeypatch: pytest.MonkeyPatch, listing: str, failing: dict[tuple[str, str], str]
) -> list[list[str]]:
    """Replace the capability module's runner: the listing, then each trial by (encoder, fmt)."""
    seen: list[list[str]] = []

    def run(command: Sequence[str]) -> tuple[int, str]:
        argv = list(command)
        seen.append(argv)
        if "-encoders" in argv:
            return 0, listing
        key = (argv[argv.index("-c:v") + 1], argv[argv.index("-pix_fmt") + 1])
        if key in failing:
            return 1, failing[key]
        return 0, ""

    monkeypatch.setattr(capability, "_run", run)
    return seen


def _caps(*rows: tuple[str, bool, tuple[int, ...]]) -> tuple[EncoderCapability, ...]:
    return tuple(
        EncoderCapability(n, ok, None if ok else "x", d, n in capability.HARDWARE_ENCODERS)
        for n, ok, d in rows
    )


def _option_values(argv: list[str], option: str) -> str:
    return argv[argv.index(option) + 1]


def _codec_p07(monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> None:
    """P07: the three rosters (CHARC round-0 ruling: the else roster keeps NVENC)."""
    assert capability.encoder_roster("win32") == ("hevc_nvenc", "libx265")
    assert capability.encoder_roster("darwin") == ("hevc_videotoolbox", "libx265")
    assert capability.encoder_roster("linux") == ("hevc_nvenc", "libx265")
    assert capability.encoder_roster(sys.platform) == capability.ENCODERS
    assert set(capability.KNOWN_ENCODERS) == {"hevc_nvenc", "hevc_videotoolbox", "libx265"}
    assert {"hevc_nvenc", "hevc_videotoolbox"} == capability.HARDWARE_ENCODERS


def _codec_p09(monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> None:
    """P09: independent 8 / 10-bit VideoToolbox trials with -allow_sw 0; a 10-bit failure only."""
    darwin = capability.encoder_roster("darwin")
    seen = _stub_ffmpeg(monkeypatch, _fixture_text("vt-encoders.txt"), {})
    both = capability._detect(Path("ffmpeg"), darwin)
    trials = [argv for argv in seen if "-encoders" not in argv]
    vt = [argv for argv in trials if _option_values(argv, "-c:v") == "hevc_videotoolbox"]
    assert sorted((_option_values(a, "-pix_fmt"), _option_values(a, "-profile:v")) for a in vt) == [
        ("p010le", "main10"),
        ("yuv420p", "main"),
    ]
    for argv in vt:
        assert _option_values(argv, "-allow_sw") == "0"
        assert not set(argv) & set(X265_ONLY_OPTIONS + NVENC_ONLY_OPTIONS)
    help_text = _fixture_text("vt-help.txt")
    assert any(line.split()[:1] == ["-allow_sw"] for line in help_text.splitlines())
