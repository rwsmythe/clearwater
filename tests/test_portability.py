_CREATE_NO_WINDOW = 0x08000000
"""Windows' CREATE_NO_WINDOW value, stubbed where the host's subprocess lacks the constant."""


def _mentions_platform(node: ast.AST) -> bool:
    return any(
        isinstance(n, ast.Attribute)
        and n.attr == "platform"
        and isinstance(n.value, ast.Name)
        and n.value.id == "sys"
        for n in ast.walk(node)
    )


def guard_form_offenders(source: str, name: str) -> list[str]:
    """Return the AD-36 guard-form violations in one module's source, by ``name:line``.

    Flagged: a conditional EXPRESSION on ``sys.platform`` (mypy narrows no attribute through
    it), and an ``if`` on ``sys.platform`` with no ``else`` whose body ends in ``return`` or
    ``raise`` (the early-return form, which leaves code after it that one platform reaches).
    """
    offenders = []
    for node in ast.walk(ast.parse(source)):
        if isinstance(node, ast.IfExp) and _mentions_platform(node.test):
            offenders.append(f"{name}:{node.lineno}")
        if (
            isinstance(node, ast.If)
            and _mentions_platform(node.test)
            and not node.orelse
            and isinstance(node.body[-1], ast.Return | ast.Raise)
        ):
            offenders.append(f"{name}:{node.lineno}")
    return offenders


def _spawn_kwargs_for(monkeypatch: pytest.MonkeyPatch, platform: str) -> dict[str, object]:
    with monkeypatch.context() as patched:
        patched.setattr(pipes.subprocess, "CREATE_NO_WINDOW", _CREATE_NO_WINDOW, raising=False)
        patched.setattr(pipes.sys, "platform", platform)
        return dict(pipes.tool_spawn_kwargs())


