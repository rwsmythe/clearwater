def _rate_p13(monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> None:
    """P13: the helper's R and level are nvenc_rate's, over the grid and recomputed."""
    for width, height, fps, level in RATE_GRID:
        for quality in ("high", "standard", "draft"):
            ceiling = encode.rate_ceiling(width, height, fps, quality, level)
            nvenc = encode.nvenc_rate(width, height, fps, quality, level)
            assert (nvenc.maxrate, nvenc.bufsize) == (ceiling.bits_per_second,) * 2
            assert nvenc.level == f"{ceiling.level_idc / 30:.1f}"
            expected = _independent_ceiling(width, height, fps, quality, level)
            assert (ceiling.bits_per_second, ceiling.level_idc) == expected
    clamped = encode.rate_ceiling(8192, 4320, Fraction(120), "high", None)
    assert (clamped.level_idc, clamped.bits_per_second) == (186, 240_000_000)
    for bad_fps in (Fraction(0), Fraction(-1)):
        with pytest.raises(ValueError, match="not positive"):
            encode.rate_ceiling(64, 48, bad_fps, "high", None)
    with pytest.raises(ValueError, match="no HEVC level"):
        encode.rate_ceiling(20000, 20000, Fraction(30), "high", None)


