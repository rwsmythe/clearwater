@pytest.mark.parametrize("encoder", ["hevc_nvenc", "libx265"])
def test_portability_windows_encoder_command_snapshot(encoder: str) -> None:
    """The NVENC and x265 sink and trial commands are byte-identical to the base's (the lock)."""
    grid = SNAPSHOT_GRID_SHA256[encoder]
    assert len(grid) == 12
    for key, digest in grid.items():
        probe_name, quality, depth = key.split("/")
        argv = snapshot_argv(encoder, probe_name, quality, int(depth))
        assert snapshot_digest(argv) == digest, key
    full = {key: argv for key, argv in SNAPSHOT_FULL.items() if key.startswith(encoder)}
    assert len(full) == 2
    for key, argv in full.items():
        _, probe_name, quality, depth = key.split("/")
        assert snapshot_argv(encoder, probe_name, quality, int(depth)) == argv, key
        assert snapshot_digest(argv) == grid[key.split("/", 1)[1]]  # the literal is the grid's
    for depth in (8, 10):
        trial = trial_encode_command(Path("ffmpeg"), encoder, depth)
        assert trial == SNAPSHOT_TRIALS[f"{encoder}/{depth}"]
