class _FakeStat:
    """A stat result with only the identity fields the queue reads."""

    def __init__(self, dev: int, ino: int) -> None:
        self.st_dev, self.st_ino = dev, ino


def _identity_provider(table: dict[str, tuple[int, int]]) -> Any:
    """A fake ``os.stat``: identity by case-folded or exact spelling, as ``table`` says."""

    def stat(path: str) -> _FakeStat:
        for spelling, (dev, ino) in table.items():
            if path.endswith(spelling):
                return _FakeStat(dev, ino)
        raise FileNotFoundError(path)

    return stat


