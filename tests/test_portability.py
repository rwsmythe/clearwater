def _fs_p73(monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> None:
    """P73: the three POSIX branches (case-only rename, link + unlink, refused-link fallback)."""
    from clearwater.config import presets

    calls: list[tuple[str, str, str]] = []

    def record(name: str, error: OSError | None = None) -> Any:
        def call(a: object, b: object = None) -> None:
            calls.append((name, Path(str(a)).name, Path(str(b)).name if b is not None else ""))
            if error is not None:
                raise error

        return call

    source, target = tmp_path / "look.json", tmp_path / "Look.json"
    cases = {
        "case-only": (True, None, [("rename", "look.json", "Look.json")]),
        "link": (False, None, [("link", "look.json", "Look.json"), ("unlink", "look.json", "")]),
        "taken": (
            False,
            FileExistsError(errno.EEXIST, "exists"),
            [("link", "look.json", "Look.json")],
        ),
        "exfat": (
            False,
            OSError(errno.EPERM, "no links"),
            [("link", "look.json", "Look.json"), ("rename", "look.json", "Look.json")],
        ),
    }
    for label, (case_only, link_error, expected) in cases.items():
        calls.clear()
        records: list[logging.LogRecord] = []
        handler = logging.Handler()
        handler.emit = records.append  # type: ignore[method-assign]
        presets._LOG.addHandler(handler)
        try:
            with monkeypatch.context() as patched:
                patched.setattr(presets, "rename_replaces", lambda: True)  # POSIX rename
                patched.setattr(presets.os, "rename", record("rename"))
                patched.setattr(presets.os, "link", record("link", link_error))
                patched.setattr(presets.os, "unlink", record("unlink"))
                if label == "taken":
                    with pytest.raises(FileExistsError):
                        presets._rename_without_replace(source, target, case_only=case_only)
                else:
                    presets._rename_without_replace(source, target, case_only=case_only)
        finally:
            presets._LOG.removeHandler(handler)
        assert calls == expected, label
        warnings = [r for r in records if r.levelno == logging.WARNING]
        assert len(warnings) == (1 if label == "exfat" else 0), label
        if warnings:
            assert "Look.json" in warnings[0].getMessage()
    for refused in (errno.EXDEV, errno.ENOTSUP, errno.EOPNOTSUPP, errno.EMLINK):
        assert refused in presets._LINKS_REFUSED
    from clearwater.config.paths import rename_replaces

    assert (rename_replaces("win32"), rename_replaces("darwin"), rename_replaces("linux")) == (
        False,
        True,
        True,
    )
    calls.clear()
    with monkeypatch.context() as patched:  # Windows keeps os.rename (it refuses a target)
        patched.setattr(presets, "rename_replaces", lambda: False)
        patched.setattr(presets.os, "rename", record("rename"))
        patched.setattr(presets.os, "link", record("link"))
        presets._rename_without_replace(source, target, case_only=False)
    assert calls == [("rename", "look.json", "Look.json")]


