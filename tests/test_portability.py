    assert store._unlink("p") is False and len(calls) == store._UNLINK_TRIES  # bounded
    outcomes[:] = [FileNotFoundError("gone")]
    assert store._unlink("p") is True
    outcomes[:] = [OSError(errno.EIO, "io")]
    assert store._unlink("p") is False


