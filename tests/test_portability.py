    assert batch_panel._key(tmp_path / "clip.MP4") == batch_panel._key(tmp_path / "CLIP.mp4")
    sensitive = {"clip.MP4": (7, 41), "CLIP.mp4": (7, 42)}  # two objects (case-sensitive APFS)
