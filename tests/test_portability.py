SOURCE, OUT = "<SOURCE>", "<OUT>"
"""Placeholders for the two host-dependent absolute paths in a sink command."""

SNAPSHOT_COMMENT = '{"app":"clearwater"}'


def snapshot_probe(name: str) -> tuple[ProbeResult, HevcLevel | None, Fraction | None]:
    """Return one of the two synthetic sources, its HEVC level and its cut (base capture's)."""
    if name == "uhd-hevc":
        video = VideoStreamInfo(
            codec="hevc",
            width=3840,
            height=2160,
            bit_depth=8,
            pix_fmt="yuv420p",
            chroma_siting="left",
            color=ColorDescription("bt709", "bt709", "bt709", "limited", 8, False, None),
            frame_rate=Fraction(60000, 1001),
            time_base=Fraction(1, 60000),
            nb_frames=600,
            rotation=0,
            vfr=False,
        )
        data = (DataStreamInfo(2, "tmcd"), DataStreamInfo(3, "gpmd"))
        level: HevcLevel | None = HevcLevel(153, False)
        cut: Fraction | None = None
    else:
        video = VideoStreamInfo(
            codec="h264",
            width=1920,
            height=1080,
            bit_depth=8,
            pix_fmt="yuv420p",
            chroma_siting="left",
            color=ColorDescription("bt709", "bt709", "bt709", "limited", 8, False, None),
            frame_rate=Fraction(30000, 1001),
            time_base=Fraction(1, 30000),
            nb_frames=300,
            rotation=90,
            vfr=False,
        )
        data = (DataStreamInfo(2, "tmcd"),)
        level = None
        cut = Fraction(1001, 300)
    probe = ProbeResult(
        path=Path("src.mp4"),
        container="mov,mp4",
        duration_s=Fraction(10),
        start_offset_s=Fraction(0),
        video=video,
        audio=(AudioStreamInfo(1, "aac", 48000, 2, Fraction(0)),),
        data=data,
        edit_list=(),
        faults=(),
        gopro=None,
    )
    return probe, level, cut


def snapshot_argv(encoder: str, probe_name: str, quality: str, bit_depth: int) -> list[str]:
    """Return the sink command for one case, its two absolute paths replaced by placeholders."""
    probe, level, cut = snapshot_probe(probe_name)
    out = Path("out.tmp")
    argv = encode_command(
        Path("ffmpeg"),
        probe,
        out,
        encoder=encoder,
        quality=quality,
        bit_depth=bit_depth,
        comment=SNAPSHOT_COMMENT,
        cut_at=cut,
        source_level=level,
    )
    source, target = str(probe.path.absolute()), str(out.absolute())
    return [SOURCE if a == source else OUT if a == target else a for a in argv]


def snapshot_digest(argv: list[str]) -> str:
    """Return the SHA-256 of the NUL-joined argument list (the grid's byte-identity key)."""
    return hashlib.sha256("\0".join(argv).encode("utf-8")).hexdigest()


