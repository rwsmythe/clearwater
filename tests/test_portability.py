def _gui_p71(qtbot: Any, monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> None:
    """P71: sub-120 deltas accumulate to one step; a 120 notch is one step; direction resets."""
    from PySide6.QtCore import QPoint, QPointF, Qt
    from PySide6.QtGui import QWheelEvent

    from clearwater.gui.preview import WHEEL_STEP_UNITS, PreviewWidget

    widget = PreviewWidget()
    qtbot.addWidget(widget)
    steps: list[str] = []
    monkeypatch.setattr(widget, "zoom_in", lambda: steps.append("in"))
    monkeypatch.setattr(widget, "zoom_out", lambda: steps.append("out"))

    def wheel(dy: int) -> None:  # a Qt event to Clearwater's own offscreen widget only
        event = QWheelEvent(
            QPointF(10, 10),
            QPointF(10, 10),
            QPoint(0, 0),
            QPoint(0, dy),
            Qt.MouseButton.NoButton,
            Qt.KeyboardModifier.NoModifier,
            Qt.ScrollPhase.NoScrollPhase,
            False,
        )
        widget.wheelEvent(event)

    assert WHEEL_STEP_UNITS == 120
    for _ in range(3):
        wheel(40)  # a trackpad: three events of 40 make one step
    assert steps == ["in"]
    wheel(120)  # one mouse notch
    wheel(-120)
    assert steps == ["in", "in", "out"]
    steps.clear()
    wheel(100)
    wheel(-30)  # a direction change drops the 100 pending
    wheel(-90)
    assert steps == ["out"]
    steps.clear()
    wheel(240)  # a two-notch event: two steps
    wheel(0)
    assert steps == ["in", "in"]


